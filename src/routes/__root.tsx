function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
        <script
          dangerouslySetInnerHTML={{
            __html: `(function(){var k="curacare-chunk-reload";function r(){try{var l=+sessionStorage.getItem(k)||0;if(Date.now()-l>10000){sessionStorage.setItem(k,String(Date.now()));location.reload();}}catch(e){}}window.addEventListener("vite:preloadError",function(e){e.preventDefault();r();});window.addEventListener("unhandledrejection",function(e){var m=String(e.reason&&e.reason.message||"");if(m.indexOf("dynamically imported module")>-1||m.indexOf("Importing a module script failed")>-1){r();}});})();`,
          }}
        />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  useEffect(() => {
    void registerServiceWorker();
    // After a new release, old pages may request files that no longer exist.
    // Reload once to pick up the latest version instead of showing a blank screen.
    const onPreloadError = (e: Event) => {
      e.preventDefault();
      const key = "curacare-chunk-reload";
      const last = Number(sessionStorage.getItem(key) || 0);
      if (Date.now() - last > 10000) {
        sessionStorage.setItem(key, String(Date.now()));
        window.location.reload();
      }
    };
    window.addEventListener("vite:preloadError", onPreloadError);
    return () => window.removeEventListener("vite:preloadError", onPreloadError);
  }, []);



  return (
    <QueryClientProvider client={queryClient}>
      <StoreProvider>
        {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
        <Outlet />
        <Toaster position="top-center" richColors />
      </StoreProvider>
    </QueryClientProvider>
  );
}
